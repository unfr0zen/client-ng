-- Each cached symbol's layer name, by its name, size and look, built once:
-- joining strings every frame costs more than drawing the symbol.
local names = {}

local function step(t, part)
  local next = t[part]
  if not next then next = {}; t[part] = next end
  return next
end

local function layer_name(name, native, o)
  local t = step(step(step(step(step(step(names, name), native), o.color or ""), o.p or 0), o.mode or ""), o.bg)
  if not t.name then
    t.name = "icon:" .. table.concat({ name, native, o.color or "", o.p or 0, o.mode or "", o.bg }, "|")
  end
  return t
end

-- A symbol drawn once, `native` units across, into a layer of its own,
-- then painted at `size`: one quad a frame instead of its shapes. A layer
-- is painted on whole pixels, so at its own size the symbol is drawn in it
-- off by what that rounding takes away (in eighths of a pixel, `o.scale`
-- pixels to a unit, `o.at` where it is when drawn translated there), and
-- lands where it falls, as stock's do.
local function sprite(gfx, name, f, x, y, size, native, o)
  -- Whole units, so the layer has as many pixels as it is across.
  local half = math.ceil(native * 0.75)
  local dx, dy = 0, 0
  if size == native then
    local s = o.scale or 1
    local function off(v)
      local p = (v - half) * s
      return math.floor((p - math.floor(p + 0.5)) * 8 + 0.5) / (8 * s)
    end
    local at = o.at or { x, y }
    dx, dy = off(at[1]), off(at[2])
  end
  local entry = layer_name(name, native, o)
  local layer = (dx == 0 and dy == 0) and entry.name or (entry.name .. "|" .. dx .. "," .. dy)
  gfx:layer(layer, layer, function(g) f(g, half + dx, half + dy, native, o) end, 2 * half, 2 * half)
  gfx:save()
  gfx:translate(x - dx, y - dy)
  gfx:scale(size / native)
  gfx:translate(-half, -half)
  gfx:paint_layer(layer, "#ffffff")
  gfx:restore()
end

-- Draws `name`, or a dot for names without a symbol. Unless `o.live`
-- (its background keeps changing) the symbol is cached: a part-selected one (`o.p` between 0 and 1) is its
-- grey and selected looks, drawn at `o.native` and `o.native_selected`
-- units, faded one over the other.
function icons.draw(gfx, name, x, y, size, o)
  o = o or {}
  if o.badge then
    local b = o.badge
    o.badge = nil
    icons.draw(gfx, name, x, y, size, o)
    o.badge = b
    return badge(gfx, x, y, size)
  end
  local f = name and icons[name]
  if type(f) ~= "function" or name == "draw" then f = icons.dot end
  o.bg = o.bg or "#000000"
  if o.live then
    return f(gfx, x, y, size, o)
  end
  local p = o.color and 1 or (o.p or 0)
  local grey = { bg = o.bg, mode = o.mode, color = o.color, p = 0, scale = o.scale, at = o.at }
  local lit = { bg = o.bg, mode = o.mode, color = o.color, p = 1, scale = o.scale, at = o.at }
  if p <= 0 then return sprite(gfx, name, f, x, y, size, o.native or size, grey) end
  if p >= 1 then return sprite(gfx, name, f, x, y, size, o.native_selected or o.native or size, lit) end
  sprite(gfx, name, f, x, y, size, o.native or size, grey)
  gfx:save()
  gfx:alpha(p)
  sprite(gfx, name, f, x, y, size, o.native_selected or o.native or size, lit)
  gfx:restore()
end

