end

-- Wi-Fi: three arcs over a dot, as stock marks a network; with `o.level`
-- (1 to 5, stock's U+E021..E025) the arcs past the signal dim.
function icons.wifi(gfx, x, y, size, o)
  local k = size / 64
  local c = tint(o, "#ffffff")
  local dim = c:sub(1, 7) .. "55"
  local lit = o and o.level and math.floor((o.level - 1) * 3 / 4 + 0.5) or 3
  local cy = y + 22 * k
  for i, r in ipairs({ 11, 21, 31 }) do
    gfx:arc(x, cy, r * k, -46, 46, 6 * k, i <= lit and c or dim)
  end
  gfx:circle(x, cy - 1 * k, 4.5 * k, c)
end

