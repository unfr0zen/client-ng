-- True Radiant: an orange heating tube in seven runs, from the left's
-- middle to the right's (matched with stock's, 68 wide at 70).
function icons.radiant(gfx, x, y, size, o)
  local k = size / 70
  local c = tint(o, "#f14f00")
  local w, r, h = 5 * k, 5.33 * k, 26.2 * k
  local pts = {}
  -- The tube's centre line, run by run: up the odd runs, down the even.
  local function run_x(i) return x + (-32 + i * 10.67) * k end
  for i = 0, 6 do
    local up = i % 2 == 0
    local from = (i == 0) and y or (up and y + h or y - h)
    local to = up and y - h or y + h
    if i == 6 then to = y - 2 * k end
    pts[#pts + 1], pts[#pts + 2] = run_x(i), from
    pts[#pts + 1], pts[#pts + 2] = run_x(i), to
    if i < 6 then
      local cx = run_x(i) + r
      -- Over the top after a run up, under after a run down.
      if up then arc_points(pts, cx, y - h, r, -90, 90, 8) else arc_points(pts, cx, y + h, r, 270, 90, 8) end
    end
  end
  for i = 1, #pts - 3, 2 do
    gfx:line(pts[i], pts[i + 1], pts[i + 2], pts[i + 3], w, c, true)
  end
end

