-- The menus' symbols, after stock's. Each is laid out on a 64-unit grid
-- centred on (x, y) and drawn `size` units across. `o.p` runs from 0 (a
-- plain grey symbol) to 1 (selected, in its own colours), or `o.color`
-- draws it in one colour; `o.bg` is the colour behind it, for cut-outs,
-- and `o.mode` the thermostat's mode, which colours the mode symbol.
local anim = require("anim")

local icons = {}

local GREY = "#656565"

local function polar(x, y, r, degrees)
  local a = math.rad(degrees)
  return x + r * math.sin(a), y - r * math.cos(a)
end

-- A colour between the grey symbol and the selected one, or the one
-- colour `o.color` asks for every part.
local function tint(o, selected)
  if o.color then return o.color end
  return anim.mix_color(GREY, selected, o.p or 0)
end

-- Points of an arc on (cx, cy), clockwise from `from` to `to` degrees.
local function arc_points(pts, cx, cy, r, from, to, n)
  for i = 0, n do
    pts[#pts + 1], pts[#pts + 2] = polar(cx, cy, r, from + (to - from) * i / n)
  end
end

-- Tools, for a change of wiring: a wrench from top left over a
-- screwdriver from top right, crossed.
function icons.tools(gfx, x, y, size, o)
  local k = size / 64
  local c = tint(o, "#bfbfbf")
  local bg = o.bg or "#000000"
  -- The wrench's handle and its open head.
  gfx:line(x + 26 * k, y + 28 * k, x - 4 * k, y - 2 * k, 13 * k, c, true)
  gfx:circle(x - 16 * k, y - 14 * k, 17 * k, c)
  gfx:line(x - 16 * k, y - 14 * k, x - 34 * k, y - 32 * k, 11 * k, bg, false)
  gfx:circle(x - 16 * k, y - 14 * k, 5 * k, bg)
  -- The screwdriver's shaft and handle.
  gfx:line(x + 26 * k, y - 28 * k, x - 2 * k, y, 7 * k, c, true)
  gfx:line(x - 2 * k, y, x - 26 * k, y + 24 * k, 15 * k, c, true)
end

-- Cancel on a confirmation: a disc with the back arrow cut out of it.
function icons.undo(gfx, x, y, size, o)
  gfx:circle(x, y, size / 2, tint(o, "#00a3d9"))
  icons.back(gfx, x + size * 0.02, y - size * 0.02, size * 0.6, { color = o.bg or "#000000" })
end

