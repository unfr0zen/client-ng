-- Airwave: a blue spiral, thin where its outer end starts top right,
-- curling in clockwise to a round end right of the middle.
function icons.airwave(gfx, x, y, size, o)
  local k = size / 70
  local outer, inner = {}, {}
  local n = 48
  for i = 0, n do
    local t = i / n
    local a = 30 + 470 * t
    local r = (34 - 22 * t) * k
    local h = math.min(1, t / 0.25) * 7 * k
    outer[#outer + 1], outer[#outer + 2] = polar(x, y + 1.5 * k, r + h, a)
    table.insert(inner, 1, select(2, polar(x, y + 1.5 * k, r - h, a)))
    table.insert(inner, 1, (polar(x, y + 1.5 * k, r - h, a)))
  end
  for i = 1, #inner do outer[#outer + 1] = inner[i] end
  local c = tint(o, "#2fb3e8")
  gfx:polygon(outer, c)
  local ex, ey = polar(x, y + 1.5 * k, 12 * k, 500)
  gfx:circle(ex, ey, 6 * k, c)
end

-- Symbols stock draws as glyphs of the unit's font: drawn so where the
-- font has them, else `fallback` (when given). A size of 47.5 (a tile's
-- symbol) draws one as stock's tiles do, at 52 px (0x1ad3dc), centred on
-- its advance, its 0.71 em height on (x, y).
local function glyph(gfx, text, x, y, size, o, fallback)
  local style = { font = "regular", size = size * 52 / 47.5, color = tint(o, "#ffffff") }
  if gfx:has_glyphs(text, style) then
    local w = gfx:measure(text, style)
    gfx:text(text, x - w / 2, y + 0.355 * style.size, style)
  elseif fallback then
    fallback()
  end
end

