-- Software: the house with two arrows chasing round inside it.
function icons.software(gfx, x, y, size, o)
  local k = size / 70
  house(gfx, x, y, k, tint(o, "#0bdbff"))
  local cx, cy, r = x - 1 * k, y + 7 * k, 12 * k
  -- Two arcs of 130 degrees each, from the top and the bottom, the head
  -- at each arc's end pointing on round (clockwise).
  for _, a in ipairs({ -30, 150 }) do
    local pts = {}
    for i = 0, 12 do
      local ang = math.rad(a + 130 * i / 12)
      pts[#pts + 1] = cx + r * math.sin(ang); pts[#pts + 1] = cy - r * math.cos(ang)
    end
    for i = 1, #pts - 2, 2 do
      gfx:line(pts[i], pts[i + 1], pts[i + 2], pts[i + 3], 4 * k, o.bg, true)
    end
    local tip = math.rad(a + 130)
    local tx, ty = cx + r * math.sin(tip), cy - r * math.cos(tip)
    local dx, dy = math.cos(tip), math.sin(tip)
    gfx:polygon({ tx + dx * 7 * k, ty + dy * 7 * k, tx - dy * 6 * k, ty + dx * 6 * k, tx + dy * 6 * k, ty - dx * 6 * k }, o.bg)
  end
end

-- Google's mark, for the legal page: a ring in its four colours, open on
