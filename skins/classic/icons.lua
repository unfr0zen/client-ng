local function draw_traced(gfx, name, x, y, size, o, colour)
  local grey = not o.color and (o.p or 0) == 0
  local parts = grey and RESTING[name] or TRACED[name]
  local k = size / (grey and 53.5 or 66)
  for n, part in ipairs(parts) do
    local pts, out = part[1], {}
    for i = 1, #pts, 2 do
      out[i], out[i + 1] = x + pts[i] * k, y + pts[i + 1] * k
    end
    local c = type(colour) == "table" and colour[n] or colour
    gfx:polygon(out, part.hole and o.bg or tint(o, c or part.colour))
  end
end

